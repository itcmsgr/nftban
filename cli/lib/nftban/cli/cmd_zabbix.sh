    - Feeds: enabled, loaded, failed, total IPs
    - Network: connections (active, established, time_wait, close_wait)
    - System: load, memory%, iowait%, disk%
    - Server inventory: hostname, OS, kernel, IPs, MAC, networks
    - GeoIP: database age, countries blocked

    Architecture: Central Collector → JSON → Zabbix Protocol
    See: nftban zabbix template --version 7.0 --output /tmp/nftban.yaml

EOF
}

# =============================================================================
# Main Command Handler
# =============================================================================
nftban_cmd_zabbix() {
    local subcommand="${1:-help}"
    shift || true

    # Show banner for non-quiet commands
    if [[ "$subcommand" != "test" || ! "$*" =~ "--quiet" ]]; then
        if [[ $(type -t nftban_banner) == "function" ]]; then
            nftban_banner "zabbix"
        fi
    fi

    case "$subcommand" in
        setup)    _cmd_zabbix_setup "$@" ;;
        status)   _cmd_zabbix_status "$@" ;;
        test)     _cmd_zabbix_test "$@" ;;
        push)     _cmd_zabbix_push "$@" ;;
        reload)   _cmd_zabbix_reload "$@" ;;
        template) _cmd_zabbix_template "$@" ;;
        discover) _cmd_zabbix_discover "$@" ;;
        targets)  _cmd_zabbix_targets "$@" ;;
        config)   _cmd_zabbix_config "$@" ;;
        help|--help|-h) _cmd_zabbix_help ;;
        *)
            _zabbix_print_error "Unknown command: $subcommand"
            _cmd_zabbix_help
            return 1
            ;;
    esac
}

# Export main handler
export -f nftban_cmd_zabbix
