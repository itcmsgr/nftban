func newTestLogger() *logging.Logger { return logging.New("/dev/null", false) }

// emptyIptablesSave returns the minimal iptables-save output a clean
// host produces (preamble only, below the 3-rule threshold).
func emptyIptablesSave() executor.Result {
	return executor.Result{
		ExitCode: 0,
		Stdout:   "# Generated by iptables-save\n*filter\n:INPUT ACCEPT\nCOMMIT\n",
	}
}

// cleanMock returns a MockExecutor that reports "no firewall of any
// kind." Tests that want to add a single firewall build on this base.
func cleanMock() *executor.MockExecutor {
	m := executor.NewMockExecutor()
	m.RunResults["iptables-save"] = emptyIptablesSave()
	m.ExistingCommands["nft"] = true
	m.RunResults["nft:list:tables"] = executor.Result{ExitCode: 0, Stdout: ""}
	return m
}

