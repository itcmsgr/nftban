# Firewall helper: Allow outbound traffic to Zabbix server
_zabbix_firewall_allow() {
    local server="$1"
    local port="$2"

    # Resolve hostname to IP if needed
    local server_ip
    if [[ "$server" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        server_ip="$server"
    else
        server_ip=$(getent hosts "$server" 2>/dev/null | awk '{print $1}' | head -1)
        [[ -z "$server_ip" ]] && server_ip=$(host "$server" 2>/dev/null | awk '/has address/ {print $4}' | head -1) || true
    fi

    [[ -z "$server_ip" ]] && return 1

    # Check if rule already exists
    if nft list chain ${NFTBAN_TABLE_IPV4} output 2>/dev/null | grep -q "daddr $server_ip.*dport $port"; then
        return 0  # Already exists
    fi

    # Add outbound rule to nftban output chain
    # Use handle-based insertion for proper priority
    if nft add rule ${NFTBAN_TABLE_IPV4} output ip daddr "$server_ip" tcp dport "$port" accept comment \"zabbix-export\" 2>/dev/null; then
        return 0
    fi

    # Fallback: Try ip family if inet doesn't exist
    if nft add rule ip nftban output ip daddr "$server_ip" tcp dport "$port" accept comment \"zabbix-export\" 2>/dev/null; then
        return 0
    fi

    return 1
}

# Firewall helper: Remove Zabbix outbound rule
_zabbix_firewall_remove() {
    local server="$1"
    local port="$2"

    # Resolve hostname to IP
    local server_ip
    if [[ "$server" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        server_ip="$server"
    else
        server_ip=$(getent hosts "$server" 2>/dev/null | awk '{print $1}' | head -1)
    fi

    [[ -z "$server_ip" ]] && return 1

    # Find and delete rule with zabbix-export comment
    local handle
    handle=$(nft -a list chain "${NFTBAN_TABLE_IPV4}" output 2>/dev/null | grep "zabbix-export" | grep -oP 'handle \K\d+')

    if [[ -n "$handle" ]]; then
        nft delete rule "${NFTBAN_TABLE_IPV4}" output handle "$handle" 2>/dev/null && return 0
    fi

    # Try ip family
    handle=$(nft -a list chain ip nftban output 2>/dev/null | grep "zabbix-export" | grep -oP 'handle \K\d+')
    if [[ -n "$handle" ]]; then
        nft delete rule ip nftban output handle "$handle" 2>/dev/null && return 0
    fi

    return 1
}

# =============================================================================
# Command: nftban zabbix setup
# =============================================================================
_cmd_zabbix_setup() {
    local server=""
    local port="10051"
    local hostname="auto"
    local tls="false"
    local psk="false"
    local interactive="true"
    local ipv4="true"
    local ipv6="false"

    # =========================================================================
    # PREREQUISITE CHECKS
    # =========================================================================
    local prereq_warnings=""

    # Check: NFTBan installed
    if [[ ! -f "${NFTBAN_CONFIG_DIR}/nftban.conf" ]]; then
        _zabbix_print_error "NFTBan not installed or configured"
        echo "  Config not found: ${NFTBAN_CONFIG_DIR}/nftban.conf"
        echo ""
        echo "Please install NFTBan first:"
        echo "  nftban install"
        return 1
    fi

    # Check: NFTBan daemon service exists
    if ! systemctl list-unit-files nftband.service &>/dev/null 2>&1; then
        prereq_warnings+="  [WARN] NFTBan daemon (nftband.service) not found - metrics may be limited\n"
    fi

    # Check: Metrics exporter — auto-enable during setup (BEFORE wizard starts)
    local metrics_enabled="${NFTBAN_METRICS_ENABLED:-false}"
    local metrics_local="${NFTBAN_CONFIG_DIR}/conf.d/metrics.conf.local"
    local global_local="${NFTBAN_CONFIG_DIR}/nftban.conf.local"
    if [[ "$metrics_enabled" != "true" ]]; then
        echo ""
        echo "  [ACTION] Metrics collection is disabled - enabling it now..."
        # Update conf.d/metrics.conf.local (used by unified exporter)
        mkdir -p "$(dirname "$metrics_local")" 2>/dev/null || true
        if [[ -f "$metrics_local" ]] && grep -q "^NFTBAN_METRICS_ENABLED=" "$metrics_local" 2>/dev/null; then
            sed -i 's/^NFTBAN_METRICS_ENABLED=.*/NFTBAN_METRICS_ENABLED="true"/' "$metrics_local"
        else
            echo 'NFTBAN_METRICS_ENABLED="true"' >> "$metrics_local"
        fi
        chmod 640 "$metrics_local" 2>/dev/null || true
        chown root:nftban "$metrics_local" 2>/dev/null || true
        # Also update nftban.conf.local (highest priority — keeps consistent with 'nftban metrics disable')
        if [[ -f "$global_local" ]] && grep -q "^NFTBAN_METRICS_ENABLED=" "$global_local" 2>/dev/null; then
            sed -i 's/^NFTBAN_METRICS_ENABLED=.*/NFTBAN_METRICS_ENABLED="true"/' "$global_local"
        fi
        # Reload the variable so rest of setup sees it
        NFTBAN_METRICS_ENABLED="true"
        echo "  [OK] Metrics config enabled"

        # Start the unified exporter service
        if systemctl list-unit-files nftban-unified-exporter.service &>/dev/null 2>&1; then
            echo "  [ACTION] Starting NFTBan unified exporter service..."
            systemctl enable nftban-unified-exporter.service &>/dev/null || true
            systemctl start nftban-unified-exporter.service &>/dev/null || true
            if systemctl is-active --quiet nftban-unified-exporter.service 2>/dev/null; then
                echo "  [OK] NFTBan exporter service started"
            else
                echo "  [WARN] Exporter service failed to start - check: systemctl status nftban-unified-exporter"
            fi
        fi
        echo ""
    fi

    # Check: Zabbix transport - use what's available, install ncat only if nothing exists
    if command -v zabbix_sender &>/dev/null; then
        : # Best option, already installed
    elif command -v ncat &>/dev/null || command -v nc &>/dev/null; then
        : # Good enough, native protocol works
    else
        # Nothing available - install ncat (in default repos)
        echo "  [ACTION] Installing ncat for Zabbix transport..."
        local distro_id
        distro_id=$(grep "^ID=" /etc/os-release 2>/dev/null | cut -d= -f2 | tr -d '"')
        case "$distro_id" in
            debian|ubuntu) apt-get install -y ncat &>/dev/null && echo "  [OK] ncat installed" || prereq_warnings+="  [WARN] apt install ncat failed\n" ;;
            centos|rhel|rocky|almalinux|fedora) dnf install -y nmap-ncat &>/dev/null && echo "  [OK] ncat installed" || prereq_warnings+="  [WARN] dnf install nmap-ncat failed\n" ;;
            *) prereq_warnings+="  [WARN] Install ncat for Zabbix: apt/dnf install ncat\n" ;;
        esac
    fi

    # Show warnings if any
    if [[ -n "$prereq_warnings" ]]; then
        echo ""
        echo "Prerequisites:"
        echo -e "$prereq_warnings"
        echo ""
    fi

    # Parse arguments
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --server)   server="$2"; shift 2 ;;
            --server=*) server="${1#*=}"; shift ;;
            --port)     port="$2"; shift 2 ;;
            --port=*)   port="${1#*=}"; shift ;;
            --hostname) hostname="$2"; shift 2 ;;
            --hostname=*) hostname="${1#*=}"; shift ;;
            --ipv4)     ipv4="true"; shift ;;
            --ipv6)     ipv6="true"; shift ;;
            --no-ipv4)  ipv4="false"; shift ;;
            --no-ipv6)  ipv6="false"; shift ;;
            --tls)      tls="true"; shift ;;
            --psk)      psk="true"; shift ;;
            --non-interactive) interactive="false"; shift ;;
            *)          shift ;;
        esac
    done

    if [[ "$interactive" == "true" && -z "$server" ]]; then
        _zabbix_print_header "NFTBan Zabbix Setup Wizard"

        echo "This wizard will configure NFTBan to push metrics to your Zabbix server."
        echo ""

        read -rp "Zabbix Server address: " server
        read -rp "Zabbix Trapper port (outbound) [10051]: " port_input
        port="${port_input:-10051}"
        read -rp "Hostname to report [auto]: " hostname_input
        hostname="${hostname_input:-auto}"

        echo ""
        echo "IP Protocol support:"
        read -rp "  Enable IPv4? [Y/n]: " ipv4_answer
        [[ "$ipv4_answer" =~ ^[Nn] ]] && ipv4="false" || ipv4="true"
        read -rp "  Enable IPv6? [y/N]: " ipv6_answer
        [[ "$ipv6_answer" =~ ^[Yy] ]] && ipv6="true"

        echo ""
        read -rp "Enable TLS encryption? [y/N]: " tls_answer
        [[ "$tls_answer" =~ ^[Yy] ]] && tls="true"

        if [[ "$tls" != "true" ]]; then
            read -rp "Enable PSK authentication? [y/N]: " psk_answer
            [[ "$psk_answer" =~ ^[Yy] ]] && psk="true" || true
        fi
    fi

    # Validate
    if [[ -z "$server" ]]; then
        _zabbix_print_error "Zabbix server address required"
        return 1
    fi

    # Auto-detect hostname if needed
    if [[ "$hostname" == "auto" ]]; then
        hostname=$(hostname -f 2>/dev/null || hostname)
    fi

    # Write config
    _zabbix_print_info "Saving configuration..."
    _zabbix_config_set "NFTBAN_ZABBIX_ENABLED" "true"
    _zabbix_config_set "NFTBAN_ZABBIX_SERVER" "$server"
    _zabbix_config_set "NFTBAN_ZABBIX_PORT" "$port"
    _zabbix_config_set "NFTBAN_ZABBIX_HOSTNAME" "$hostname"
    _zabbix_config_set "NFTBAN_ZABBIX_TLS_ENABLED" "$tls"
    _zabbix_config_set "NFTBAN_ZABBIX_PSK_ENABLED" "$psk"

    # Note: Metrics collection is enabled at the start of setup (prerequisites phase)

    # Configure firewall for outbound Zabbix traffic
    local firewall_auto
    firewall_auto=$(_zabbix_config_get "NFTBAN_ZABBIX_FIREWALL_AUTO" "true")
    if [[ "$firewall_auto" == "true" ]]; then
        _zabbix_print_info "Configuring firewall for outbound traffic to $server:$port..."

        # Default to both IPv4 and IPv6 if neither was explicitly selected
        if [[ "$ipv4" == "false" && "$ipv6" == "false" ]]; then
            ipv4="true"
            ipv6="true"
        fi

        # Check if port already exists in ports.d
        # Format is PORT/PROTO/DIR where PROTO=T(tcp)|U(udp)|B(both) and DIR=I(in)|O(out)|IO(inout)
        local port_exists=false
        local existing_file=""
        for f in "${NFTBAN_CONFIG_DIR}/ports.d"/*.conf; do
            [[ -f "$f" ]] || continue
            # Check for output (O) or inout (IO) direction
            if grep -qE "^${port}/T/(O|IO)$" "$f" 2>/dev/null; then
                port_exists=true
                existing_file="$f"
                break
            fi
        done

        if [[ "$port_exists" == "true" ]]; then
            _zabbix_print_info "Port $port/tcp output already configured in: $existing_file"
        else
            # Use nftban port add command (single point of truth)
            # Syntax: nftban port add <port> <protocol> <direction>
            # Direction: in, out, inout
            _zabbix_print_info "Adding port $port/tcp (output) via nftban port add..."

            # Use nftban port add with positional arguments
            if nftban port add "$port" tcp out 2>/dev/null; then
                _zabbix_print_success "Port $port/tcp (output) added to firewall"
            else
                # Fallback: create config directly using correct format
                local port_conf="${NFTBAN_CONFIG_DIR}/ports.d/99-zabbix.conf"
                mkdir -p "$(dirname "$port_conf")" || return 1

                cat > "$port_conf" << EOF
# =============================================================================
# NFTBan - Zabbix Server Connection (Auto-generated)
# =============================================================================
# Created: $(date '+%Y-%m-%d %H:%M:%S')
# Server:  $server
# Purpose: Allow outbound metrics push to Zabbix trapper port
# Format:  PORT/PROTO/DIR where PROTO=T(tcp)|U(udp)|B(both), DIR=I(in)|O(out)|IO(inout)
# =============================================================================

# Zabbix trapper port - OUTBOUND connection to monitoring server
# Added by: nftban zabbix setup ($(date '+%Y-%m-%d %H:%M:%S'))
${port}/T/O
EOF
                chmod 640 "$port_conf"
                chown root:nftban "$port_conf" 2>/dev/null || true
                _zabbix_print_success "Port configuration saved: $port_conf"
            fi
        fi

        # Apply runtime firewall rule (nft is live - no reload needed)
        if _zabbix_firewall_allow "$server" "$port"; then
            _zabbix_print_success "Firewall rule applied (live)"
        else
            _zabbix_print_warning "Could not apply firewall rule (manual setup may be required)"
        fi
    fi

    # Enable unified exporter timer
    _zabbix_print_info "Enabling unified exporter timer..."
    if systemctl enable --now nftban-unified-exporter.timer 2>/dev/null; then
        _zabbix_print_success "Timer enabled"
    else
        _zabbix_print_warning "Could not enable timer (run: systemctl enable --now nftban-unified-exporter.timer)"
    fi

    # Test connection
    echo ""
    _zabbix_print_info "Testing connection..."
    if _cmd_zabbix_test --quiet; then
        _zabbix_print_success "Zabbix integration configured successfully"
        echo ""
        echo "Configuration saved to: ${NFTBAN_CONFIG_DIR}/conf.d/zabbix.conf.local"
        echo ""
        echo "Next steps:"
        echo "  1. Import template: nftban zabbix template --version 6.0 --output /tmp/nftban.yaml"
        echo "  2. Link template to host in Zabbix UI"
        echo "  3. Verify: nftban zabbix status"
    else
        _zabbix_print_warning "Configuration saved but connection test failed"
        echo ""
        echo "Troubleshooting:"
        echo "  - Check server address and port"
        echo "  - Verify firewall allows port $port"
        echo "  - Ensure Zabbix server is running"
        echo "  - Run: nftban zabbix test --verbose"
    fi
}

# =============================================================================
# Command: nftban zabbix status
# =============================================================================
_cmd_zabbix_status() {
    local json="false"
    local verbose="false"

    while [[ $# -gt 0 ]]; do
        case "$1" in
            --json)    json="true"; shift ;;
            --verbose) verbose="true"; shift ;;
            *)         shift ;;
        esac
    done

    # Load config values
    local enabled server port hostname interval tls psk
    enabled=$(_zabbix_config_get "NFTBAN_ZABBIX_ENABLED" "false")
    server=$(_zabbix_config_get "NFTBAN_ZABBIX_SERVER" "")
    port=$(_zabbix_config_get "NFTBAN_ZABBIX_PORT" "10051")
    hostname=$(_zabbix_config_get "NFTBAN_ZABBIX_HOSTNAME" "auto")
    interval=$(_zabbix_config_get "NFTBAN_ZABBIX_INTERVAL" "60")
    tls=$(_zabbix_config_get "NFTBAN_ZABBIX_TLS_ENABLED" "false")
    psk=$(_zabbix_config_get "NFTBAN_ZABBIX_PSK_ENABLED" "false")

    # Get actual hostname if auto
    local actual_hostname="$hostname"
    if [[ "$hostname" == "auto" ]]; then
        actual_hostname=$(hostname -f 2>/dev/null || hostname)
    fi

    if [[ "$json" == "true" ]]; then
        cat <<EOF
{
  "enabled": $enabled,
  "server": "$server",
  "trapper_port": $port,
  "hostname": "$actual_hostname",
  "interval": $interval,
  "tls_enabled": $tls,
  "psk_enabled": $psk
}
EOF
        return 0
    fi

    _zabbix_print_header "NFTBan Zabbix Integration Status"

    echo "Configuration:"
    if [[ "$enabled" == "true" ]]; then
        echo "  Enabled:      ✅ true"
    else
        echo "  Enabled:      ❌ false"
    fi
    echo "  Server:       ${server:-not configured}"
    echo "  Hostname:     $actual_hostname"
    echo ""
    echo "Ports:"
    echo "  Trapper:      $port/tcp (outbound - push metrics to server)"
    echo ""
    echo "Options:"
    echo "  Interval:     ${interval}s"
    echo "  TLS:          $tls"
    echo "  PSK:          $psk"
    echo ""

    # Check exporter timer status
    echo "Exporter Service:"
    if systemctl is-active nftban-unified-exporter.timer &>/dev/null; then
        echo "  Timer:      ✅ Active"
        local last_run
        last_run=$(systemctl show nftban-unified-exporter.timer -p LastTriggerUSec --value 2>/dev/null || echo "n/a")
        if [[ -n "$last_run" ]] && [[ "$last_run" != "n/a" ]]; then
            echo "  Last run:   $(date -d "$last_run" '+%Y-%m-%d %H:%M:%S' 2>/dev/null || echo "$last_run")"
        fi
    elif systemctl list-unit-files nftban-unified-exporter.timer &>/dev/null 2>&1; then
        echo "  Timer:      ⚠️  Installed but not active"
        echo "              Enable with: systemctl enable --now nftban-unified-exporter.timer"
    else
        echo "  Timer:      ℹ️  Not installed (using bash fallback)"
    fi
    echo ""

    # Check zabbix_sender availability
    echo "Dependencies:"
    if command -v zabbix_sender &>/dev/null; then
        local sender_version
        sender_version=$(zabbix_sender -V 2>&1 | head -1 || echo "unknown")
        echo "  zabbix_sender: ✅ $sender_version"
    else
        echo "  zabbix_sender: ⚠️  Not installed (using native protocol)"
        echo "                 Install: apt install zabbix-sender  # or yum/dnf"
    fi
    echo ""

    # Show quick start guide if not configured
    if [[ "$enabled" != "true" ]] || [[ -z "$server" ]]; then
        echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
        echo "  Quick Start Guide"
        echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
        echo ""
        echo "Step 1: Configure Zabbix server connection"
        echo "  nftban zabbix setup --server YOUR_ZABBIX_SERVER"
        echo ""
        echo "Step 2: Import template into Zabbix"
        echo "  # Export template file:"
        echo "  nftban zabbix template --version 7.0 --output /tmp/nftban.yaml"
        echo ""
        echo "  # In Zabbix UI: Data collection → Templates → Import"
        echo "  # Select the exported file and click Import"
        echo ""
        echo "Step 3: Link template to host"
        echo "  # In Zabbix UI: Data collection → Hosts → Your Host → Templates"
        echo "  # Link the 'NFTBan' template"
        echo ""
        echo "Step 4: Verify metrics are flowing"
        echo "  nftban zabbix test --verbose"
        echo "  nftban zabbix push"
        echo ""
        echo "For more help:"
        echo "  nftban zabbix help"
        echo "  https://nftban.com/docs/zabbix"
        echo ""
    else
