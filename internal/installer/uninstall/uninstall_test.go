func happyClassify() *ClassifyResult {
	return &ClassifyResult{State: AuthorityNFTBan}
}

func noPriorProbe() *ProbeResult {
	return &ProbeResult{State: PriorNoRecord}
}

func usablePriorProbe() *ProbeResult {
	return &ProbeResult{
		State:  PriorRecordUsable,
		Record: &PriorRecord{SchemaVersion: PlanSchemaVersion, FirewallType: "ufw", ActiveAtInstall: true},
	}
}

func TestBuildPlan_Remove_Defaults(t *testing.T) {
	p := BuildPlan(ModeRemove, happyClassify(), noPriorProbe(), false)
	if p.RequestedMode != ModeRemove {
		t.Errorf("RequestedMode = %q; want %q", p.RequestedMode, ModeRemove)
	}
	if p.TargetAuthority != AuthorityNone {
		t.Errorf("TargetAuthority = %q; want %q (Q2=C default is None)", p.TargetAuthority, AuthorityNone)
	}
	if p.RestoreRequested || p.RestoreAuthorized {
		t.Error("restore flags must be false by default")
	}
}

func TestBuildPlan_Purge_PreservesConfLocal_ArtifactPolicy(t *testing.T) {
	p := BuildPlan(ModePurge, happyClassify(), noPriorProbe(), false)
	if !strings.Contains(p.ArtifactPolicy, "preserve .conf.local") {
		t.Errorf("purge ArtifactPolicy must mention .conf.local preservation (Q3=B); got: %s", p.ArtifactPolicy)
	}
}

func TestBuildPlan_PurgeForceDOC_DescribesConfLocalDelete(t *testing.T) {
	p := BuildPlan(ModePurgeForceDOC, happyClassify(), noPriorProbe(), false)
	if !strings.Contains(p.ArtifactPolicy, "delete .conf.local") {
		t.Errorf("purge+force ArtifactPolicy must describe .conf.local deletion; got: %s", p.ArtifactPolicy)
	}
}

func TestBuildPlan_Restore_UsableRecord_Authorized(t *testing.T) {
	p := BuildPlan(ModeRemove, happyClassify(), usablePriorProbe(), true)
	if !p.RestoreAuthorized {
		t.Error("restore must be authorized when prior record is usable AND flag is set (Q4=B)")
	}
	if p.TargetAuthority != CurrentAuthority("ufw") {
		t.Errorf("TargetAuthority = %q; want ufw (restored prior)", p.TargetAuthority)
	}
}

func TestBuildPlan_Restore_NoRecord_NotAuthorized(t *testing.T) {
	p := BuildPlan(ModeRemove, happyClassify(), noPriorProbe(), true)
	if p.RestoreAuthorized {
		t.Error("restore must NOT be authorized when no prior record exists (Q4=B + §10.2 B-UN-restore-norecord)")
	}
	// A warning must surface for the operator.
	var found bool
	for _, w := range p.Warnings {
		if strings.Contains(w, "no prior-authority record") {
			found = true
		}
	}
	if !found {
		t.Error("plan must warn when restore requested but no record exists; PR-24 will enforce")
	}
}

func TestBuildPlan_Restore_IncompleteRecord_NotAuthorized(t *testing.T) {
	prior := &ProbeResult{State: PriorRecordIncomplete}
	p := BuildPlan(ModeRemove, happyClassify(), prior, true)
	if p.RestoreAuthorized {
		t.Error("restore must NOT be authorized when prior record is incomplete")
	}
	var found bool
	for _, w := range p.Warnings {
		if strings.Contains(w, "incomplete") {
			found = true
		}
	}
	if !found {
		t.Error("plan must warn when restore requested but record is incomplete")
	}
}

// Render output — contract-language structural checks

func TestRender_HasMandatoryFieldsAndScopeBoundary(t *testing.T) {
	p := BuildPlan(ModeRemove, happyClassify(), noPriorProbe(), false)
	var buf bytes.Buffer
	p.Render(&buf)
	out := buf.String()

	mustHave := []string{
		"NFTBan Uninstall — Plan",
		"Requested mode",
		"Artifact policy",
		"Current authority",
		"Target authority",
		"Restore requested",
		"Restore authorized",
		"Prior-authority record",
		"Phases that would mutate (NOT IMPLEMENTED in PR-22):",
		"Scope boundary:",
		"Running this command does NOT uninstall nftban",
		"later PRs in the v1.100 track must land first",
	}
	for _, needle := range mustHave {
		if !strings.Contains(out, needle) {
			t.Errorf("Render output missing mandatory contract-language element %q", needle)
		}
	}
}

func TestRender_ScopeBoundaryBlock_AlwaysPresent_AllModes(t *testing.T) {
	// The scope-boundary block is MANDATORY regardless of mode; a future
	// change that branches it away for certain modes would violate the
	// PR-22 contract.
	for _, mode := range []Mode{ModeRemove, ModePurge, ModePurgeForceDOC} {
		p := BuildPlan(mode, happyClassify(), noPriorProbe(), false)
		var buf bytes.Buffer
		p.Render(&buf)
		if !strings.Contains(buf.String(), "Scope boundary:") {
			t.Errorf("mode %q: scope-boundary block missing", mode)
		}
	}
}

func TestPlan_JSON_RoundTrip_KeyFields(t *testing.T) {
	p := BuildPlan(ModePurge, happyClassify(), usablePriorProbe(), true)
	data, err := p.JSON()
	if err != nil {
		t.Fatalf("JSON encode: %v", err)
	}
	out := string(data)
	for _, needle := range []string{
		`"schema_version"`,
		`"requested_mode": "purge"`,
		`"restore_requested": true`,
		`"restore_authorized": true`,
		`"prior_state": "record_usable"`,
		`"phases_that_would_mutate"`,
	} {
		if !strings.Contains(out, needle) {
			t.Errorf("JSON output missing %s:\n%s", needle, out)
		}
	}
}
