func TestClassify_NoteOnPartialNFTBan(t *testing.T) {
	// ip nftban table present but daemon NOT active → should note the
	// inconsistency but not claim authority.
	mock := executor.NewMockExecutor()
	mock.NftTables["ip:nftban"] = true

	res := Classify(mock, newTestLogger())
	// Classification must not be AuthorityNFTBan (daemon is down).
	if res.State == AuthorityNFTBan {
		t.Error("partial nftban should NOT classify as AuthorityNFTBan")
	}
	// A note must surface the partial state.
	var found bool
	for _, n := range res.Notes {
		if strings.Contains(n, "nftband.service inactive") {
			found = true
		}
	}
	if !found {
		t.Error("partial-nftban warning note missing; operator must see the inconsistency")
	}
}

