func TestDetect_Iptables_AllThreeSignals(t *testing.T) {
	// Service signal
	m := cleanMock()
	m.Services["iptables.service"] = true
	if res := Detect(m, newTestLogger()); res.Authoritative != NameIptables {
		t.Errorf("service: Authoritative = %q; want iptables", res.Authoritative)
	}

	// Ghost-table signal (filter table, common iptables-nft case)
	m2 := cleanMock()
	m2.RunResults["nft:list:tables"] = executor.Result{ExitCode: 0, Stdout: "table ip filter\n"}
	if res := Detect(m2, newTestLogger()); res.Authoritative != NameIptables {
		t.Errorf("ghost-table: Authoritative = %q; want iptables", res.Authoritative)
	}

	// Active-rules signal (iptables-save)
	m3 := cleanMock()
	m3.RunResults["iptables-save"] = executor.Result{
		ExitCode: 0,
		Stdout:   "# Generated\n*filter\n:INPUT ACCEPT\n-A INPUT -j ACCEPT\n-A INPUT -p tcp --dport 22 -j ACCEPT\n-A INPUT -p tcp --dport 80 -j ACCEPT\nCOMMIT\n",
	}
	if res := Detect(m3, newTestLogger()); res.Authoritative != NameIptables {
		t.Errorf("iptables-save: Authoritative = %q; want iptables", res.Authoritative)
	}
}

// PR-P2-2 Option A RESOLUTION: /etc/csf/csf.conf alone (no running
// service) must produce CSF=active across ALL callers. This test is
// the locked regression guard for the unification decision. Pre-PR-P2-2
// the install side ignored the config-file signal; after PR-P2-2 every
// caller sees the same answer.
func TestDetect_CSF_ConfigFileOnly(t *testing.T) {
	m := cleanMock()
	m.Files["/etc/csf/csf.conf"] = []byte("# csf config stub for test\n")
	// Neither csf.service nor lfd.service active — config-only remnant.

	res := Detect(m, newTestLogger())
	if res.Authoritative != NameCSF {
		t.Errorf("Authoritative = %q; want csf (config-file-only remnant must be detected — Option A)", res.Authoritative)
	}
	if res.Ambiguous {
		t.Error("single CSF signal must not be Ambiguous")
	}
	// The observation must carry the config-file source so consumers
	// that care (e.g. future DisableConflicts branch) can distinguish
	// from a live-service detection.
	var haveConfigObs bool
	for _, o := range res.Observations {
		if o.Name == NameCSF && o.Source == SourceConfigFile {
			haveConfigObs = true
		}
	}
	if !haveConfigObs {
		t.Errorf("CSF config-file observation missing; got Observations=%+v", res.Observations)
	}
}

func TestDetect_CSF_BothServicesActive(t *testing.T) {
	m := cleanMock()
	m.Services["csf.service"] = true
	m.Services["lfd.service"] = true

	res := Detect(m, newTestLogger())
	if res.Authoritative != NameCSF {
		t.Errorf("Authoritative = %q; want csf", res.Authoritative)
	}
	// Two observations (one per unit) — DisableConflicts relies on
	// seeing both units so it can stop+disable+mask each.
	var csfUnits int
	for _, o := range res.Observations {
		if o.Name == NameCSF && o.Source == SourceService {
			csfUnits++
		}
	}
	if csfUnits != 2 {
		t.Errorf("expected 2 CSF service observations (csf + lfd); got %d", csfUnits)
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// Multi-firewall case — MUST be Ambiguous, no silent collapse
// ─────────────────────────────────────────────────────────────────────────────

// PR-P2-2 hard rule: multiple active firewalls do NOT collapse via
// precedence. The detector surfaces Ambiguous and the caller decides
// how to handle it.
func TestDetect_MultipleActive_IsAmbiguous_NoSilentCollapse(t *testing.T) {
	m := cleanMock()
	m.Services["ufw.service"] = true
	m.Services["firewalld.service"] = true // should NOT silently lose to ufw

	res := Detect(m, newTestLogger())
	if !res.Ambiguous {
		t.Error("multi-active host MUST be Ambiguous; detector is collapsing via precedence")
	}
	if res.Authoritative != NameNone {
		t.Errorf("Authoritative = %q on multi-active host; must be NameNone when Ambiguous", res.Authoritative)
	}
	if len(res.Active) != 2 {
		t.Errorf("Active list should have 2 entries; got %v", res.Active)
	}
	// Active list must be in locked precedence order.
	if res.Active[0] != NameUFW || res.Active[1] != NameFirewalld {
		t.Errorf("Active not in precedence order; got %v, want [ufw firewalld]", res.Active)
	}
}

func TestDetect_AllFourActive_IsAmbiguous(t *testing.T) {
	m := cleanMock()
	m.Services["ufw.service"] = true
	m.Services["firewalld.service"] = true
	m.Services["iptables.service"] = true
	m.Services["csf.service"] = true

	res := Detect(m, newTestLogger())
	if !res.Ambiguous {
		t.Error("4-way multi-active must be Ambiguous")
	}
	if len(res.Active) != 4 {
		t.Errorf("Active should have all 4 names; got %v", res.Active)
	}
	// Locked precedence order must be preserved.
	want := []Name{NameUFW, NameFirewalld, NameIptables, NameCSF}
	for i, w := range want {
		if res.Active[i] != w {
			t.Errorf("Active[%d] = %q; want %q (precedence order)", i, res.Active[i], w)
		}
	}
}

// ─────────────────────────────────────────────────────────────────────────────
// Precedence + same-firewall multi-signal coalescing
// ─────────────────────────────────────────────────────────────────────────────

// Multiple signals for the SAME firewall do NOT trigger Ambiguous —
// they agree, so the result is the single firewall. Only DIFFERENT
// firewalls triggering simultaneously count as ambiguous.
func TestDetect_SameFirewallMultiSignal_IsNotAmbiguous(t *testing.T) {
	m := cleanMock()
	m.Services["csf.service"] = true
	m.Services["lfd.service"] = true
	m.Files["/etc/csf/csf.conf"] = []byte("# config\n")
	// Three signals, all saying CSF.

	res := Detect(m, newTestLogger())
	if res.Ambiguous {
		t.Error("same-firewall multi-signal must NOT be Ambiguous")
	}
	if res.Authoritative != NameCSF {
		t.Errorf("Authoritative = %q; want csf (all signals agree)", res.Authoritative)
	}
	if len(res.Observations) < 3 {
		t.Errorf("expected ≥3 CSF observations; got %d", len(res.Observations))
	}
}

// Precedence lock test: with only two distinct firewalls active, the
// Active list must show them in the frozen order. This is the
// regression guard for "precedence changes unintentionally."
func TestDetect_PrecedenceOrder_Frozen(t *testing.T) {
	m := cleanMock()
	// Intentionally set in reverse of precedence order to prove the
	// result is order-independent of mock setup.
	m.Services["csf.service"] = true
	m.Services["ufw.service"] = true

	res := Detect(m, newTestLogger())
	if !res.Ambiguous {
		t.Fatal("two distinct firewalls must be Ambiguous")
	}
	if res.Active[0] != NameUFW || res.Active[1] != NameCSF {
		t.Errorf("Active = %v; want [ufw csf] per locked precedence ufw→firewalld→iptables→csf", res.Active)
	}
}

