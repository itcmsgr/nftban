_zabbix_config_get() {
    # Get config value (variable is already loaded from .conf/.conf.local)
    # Args: $1 = key name, $2 = default value
    local key="$1"
    local default="${2:-}"
    local value="${!key:-}"
    echo "${value:-$default}"
}

_zabbix_config_set() {
    # Write config to zabbix.conf.local (module-specific for proper permissions)
    # The unified exporter runs as 'nftban' user and needs read access
    local key="$1"
    local value="$2"
    local conf_local="${NFTBAN_CONFIG_DIR}/conf.d/zabbix.conf.local"

    mkdir -p "$(dirname "$conf_local")" || return 1
    if [[ ! -f "$conf_local" ]]; then
        cat > "$conf_local" <<'EOF'
# NFTBan - Zabbix User Overrides
# Auto-generated by: nftban zabbix setup
# This file is read by nftban-unified-exporter.service (runs as nftban user)
EOF
        chown root:nftban "$conf_local" 2>/dev/null || true
        chmod 640 "$conf_local"
    fi

    if grep -qE "^${key}=" "$conf_local" 2>/dev/null; then
        sed -i "s|^${key}=.*|${key}=\"${value}\"|" "$conf_local"
    else
        echo "${key}=\"${value}\"" >> "$conf_local"
    fi

    # Update in-memory variable
    declare -g "$key"="$value"
}

